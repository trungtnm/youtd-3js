// Writes src/sim/sim-build.js: a hash of every file the simulation is built from.
// A run log records the build it was played on, and the server only verifies logs
// from the build it runs, since any rule or data change can change a replay.
// Runs before dev, build and deploy (npm pre-scripts); `--check` fails when stale.

import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { join, relative } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname;
const OUT = join(ROOT, 'src/sim/sim-build.js');
const DIRS = ['src/sim', 'src/data'];

function files(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const p = join(dir, e.name);
    return e.isDirectory() ? files(p) : e.name.endsWith('.js') && p !== OUT ? [p] : [];
  });
}

const hash = createHash('sha256');
for (const f of DIRS.flatMap((d) => files(join(ROOT, d))).sort()) {
  hash.update(relative(ROOT, f));
  hash.update('\0');
  hash.update(readFileSync(f));
}
const id = hash.digest('hex').slice(0, 12);
const text = `// Generated by tools/sim-build.mjs; do not edit. Hash of src/sim and src/data.\nexport const SIM_BUILD = '${id}';\n`;

if (process.argv.includes('--check')) {
  const cur = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (cur !== text) { console.error('src/sim/sim-build.js is stale: run node tools/sim-build.mjs'); process.exit(1); }
} else if (!existsSync(OUT) || readFileSync(OUT, 'utf8') !== text) {
  writeFileSync(OUT, text);
  console.log(`sim build ${id}`);
}
